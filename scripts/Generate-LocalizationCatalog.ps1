param(
    [string]$ResourcesDirectory = (Join-Path $PSScriptRoot '../src/Cafe.Launcher.UI/Resources'),
    [string]$OutputDirectory = (Join-Path $PSScriptRoot '../src/Cafe.Launcher.UI'),
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$tables = @{}
foreach ($locale in @('', 'zh-Hans', 'zh-Hant', 'ja')) {
    $suffix = if ($locale) { ".$locale" } else { '' }
    [xml]$document = Get-Content -LiteralPath (Join-Path $ResourcesDirectory "LauncherStrings$suffix.resx") -Raw -Encoding utf8
    $table = [System.Collections.Generic.Dictionary[string,string]]::new([System.StringComparer]::Ordinal)
    foreach ($entry in $document.root.data) {
        if ([string]::IsNullOrWhiteSpace($entry.value)) { throw "Empty resource: $locale/$($entry.name)" }
        if ($table.ContainsKey($entry.name)) { throw "Duplicate resource key: $locale/$($entry.name)" }
        $table.Add($entry.name, $entry.value)
        # Validate composite-format syntax without requiring the .NET 8-only
        # CompositeFormat API: supported PowerShell 7 runtimes may be older.
        # Null arguments exercise parsing without imposing a value type on format specifiers.
        $argumentCount = 0
        foreach ($argument in [regex]::Matches($entry.value, '\{(?<index>\d+)')) {
            $argumentCount = [Math]::Max($argumentCount, 1 + [int]$argument.Groups['index'].Value)
        }
        try {
            $null = [string]::Format([System.Globalization.CultureInfo]::InvariantCulture,
                [string]$entry.value, [object[]]::new($argumentCount))
        }
        catch { throw "Invalid resource format: $locale/$($entry.name)" }
    }
    $tables[$locale] = $table
}
$keys = [string[]]@($tables[''].Keys)
[Array]::Sort($keys, [System.StringComparer]::Ordinal)
if ($keys.Count -eq 0) { throw 'The neutral catalog is empty.' }
foreach ($locale in @('zh-Hans', 'zh-Hant', 'ja')) {
    $table = $tables[$locale]
    if ($table.Count -ne $keys.Count) { throw "Resource key set mismatch: $locale" }
    foreach ($key in $keys) {
        if (-not $table.ContainsKey($key)) { throw "Resource key set mismatch: $locale/$key" }
    }
    foreach ($key in $keys) {
        $pattern = '\{\{|\}\}|\{(?<index>\d+)[^}]*\}'
        $expected = @([regex]::Matches($tables[''][$key], $pattern) | Where-Object { $_.Groups['index'].Success } | ForEach-Object { $_.Groups['index'].Value } | Sort-Object)
        $actual = @([regex]::Matches($table[$key], $pattern) | Where-Object { $_.Groups['index'].Success } | ForEach-Object { $_.Groups['index'].Value } | Sort-Object)
        if (($expected -join ',') -cne ($actual -join ',')) { throw "Placeholder mismatch: $locale/$key" }
    }
}

# XAML bindings are the string adapter; validate them in every ordinary build.
$sourceRoot = Split-Path $OutputDirectory -Parent
foreach ($file in Get-ChildItem -LiteralPath $sourceRoot -Recurse -Filter '*.axaml' | Where-Object { $_.FullName -notmatch '[\\/](bin|obj)[\\/]' }) {
    $content = Get-Content -LiteralPath $file.FullName -Raw -Encoding utf8
    $content = [regex]::Replace($content, '(?s)<!--.*?-->', '')
    foreach ($match in [regex]::Matches($content, 'I18n\[\s*[''"]?(?<key>[^]\s''"]+)[''"]?\s*\]')) {
        if (-not $tables[''].ContainsKey($match.Groups['key'].Value)) { throw "$($file.FullName): Unknown localization key $($match.Groups['key'].Value)" }
    }
}

$identifiers = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
$members = foreach ($key in $keys) {
    $name = (($key -split '[^A-Za-z0-9]+' | Where-Object { $_ } | ForEach-Object { [char]::ToUpperInvariant($_[0]) + $_.Substring(1) }) -join '')
    if ($name -notmatch '^[A-Za-z]') { $name = "Key$name" }
    if (-not $identifiers.Add($name)) { throw "Identifier collision: $key" }
    "    $name,"
}
$enum = @"
// <auto-generated>Generated by scripts/Generate-LocalizationCatalog.ps1.</auto-generated>
namespace Cafe.Launcher.UI.Constants;

/// <summary>Validated names from the neutral resource catalog; raw strings belong only at the XAML adapter.</summary>
public enum LocalizationKeys
{
$($members -join "`n")
}
"@
$names = ($keys | ForEach-Object { '        "' + $_ + '",' }) -join "`n"
$catalog = @"
// <auto-generated>Generated by scripts/Generate-LocalizationCatalog.ps1.</auto-generated>
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Resources;
using Cafe.Launcher.UI.Constants;

namespace Cafe.Launcher.UI.Resources;

/// <summary>Owns the generated key set, string adapter, and embedded-resource validation.</summary>
internal static class LauncherResourceCatalog
{
    private static readonly string[] Names =
    [
$names
    ];
    private static readonly Lazy<bool> Validated = new(ValidateResources);
    private static readonly Dictionary<string, LocalizationKeys> Keys = CreateKeys();

    public static string Name(LocalizationKeys key) => (uint)key < Names.Length
        ? Names[(int)key] : throw new ArgumentOutOfRangeException(nameof(key));

    public static LocalizationKeys Parse(string key) => Keys.TryGetValue(key, out var value)
        ? value : throw new ArgumentException("Unknown localization key: " + key, nameof(key));

    public static void EnsureValid() => _ = Validated.Value;

    private static Dictionary<string, LocalizationKeys> CreateKeys()
    {
        var keys = new Dictionary<string, LocalizationKeys>(StringComparer.Ordinal);
        for (var i = 0; i < Names.Length; i++) keys.Add(Names[i], (LocalizationKeys)i);
        return keys;
    }

    private static bool ValidateResources()
    {
        foreach (var culture in new[] { CultureInfo.InvariantCulture, new CultureInfo("zh-Hans"), new CultureInfo("zh-Hant"), new CultureInfo("ja") })
        {
            var resources = LauncherStrings.ResourceManager.GetResourceSet(culture, true, false)
                ?? throw new MissingManifestResourceException("Missing resource set: " + culture.Name);
            foreach (var name in Names)
            {
                if (string.IsNullOrWhiteSpace(resources.GetString(name)))
                    throw new MissingManifestResourceException("Missing resource: " + culture.Name + "/" + name);
            }
        }
        return true;
    }
}
"@
$manager = @'
// <auto-generated>Generated by scripts/Generate-LocalizationCatalog.ps1.</auto-generated>
using System.Resources;
namespace Cafe.Launcher.UI.Resources;

/// <summary>Embedded manager used by the generated catalog.</summary>
internal static class LauncherStrings
{
    public static ResourceManager ResourceManager { get; } = new(
        "Cafe.Launcher.UI.Resources.LauncherStrings", typeof(LauncherStrings).Assembly);
}
'@
$outputs = @{
    'Constants/LocalizationKeys.cs' = $enum
    'Resources/LauncherResourceCatalog.Generated.cs' = $catalog
    'Resources/LauncherStrings.Designer.cs' = $manager
}
foreach ($relative in $outputs.Keys) {
    $path = Join-Path $OutputDirectory $relative
    $content = ($outputs[$relative].TrimEnd() + "`n") -replace "`r?`n", "`r`n"
    $existing = if (Test-Path -LiteralPath $path) { [System.IO.File]::ReadAllText($path) } else { '' }
    if (($existing -replace "`r`n", "`n") -ceq ($content -replace "`r`n", "`n")) { continue }
    if ($Check) { throw "Generated localization catalog is stale: $path. Run scripts/Generate-LocalizationCatalog.ps1." }
    [System.IO.File]::WriteAllText($path, $content, [System.Text.UTF8Encoding]::new($false))
}
