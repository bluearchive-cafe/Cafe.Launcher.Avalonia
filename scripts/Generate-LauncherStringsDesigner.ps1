param(
    [string]$ResourceFile = (Join-Path $PSScriptRoot '..\src\Cafe.Launcher.UI\Resources\LauncherStrings.resx'),
    [string]$OutputFile = (Join-Path $PSScriptRoot '..\src\Cafe.Launcher.UI\Resources\LauncherStrings.Designer.cs')
)

$ErrorActionPreference = 'Stop'

# Emit and decode console output as UTF-8 so Chinese text (commit messages,
# resx values, tool output) survives the system's active code page.
try { [Console]::OutputEncoding = [System.Text.Encoding]::UTF8 } catch { }

# 只生成 ResourceManager：生产侧从不消费 strongly typed accessors（调用点走
# Constants/LocalizationKeys + LocalizationService.T），第二份全量投影只会随 key 一起漂移。
if (-not (Test-Path -LiteralPath $ResourceFile)) {
    throw "Neutral resource file was not found: $ResourceFile"
}

[xml]$resourceDocument = Get-Content -LiteralPath $ResourceFile -Raw -Encoding UTF8
$keyCount = @($resourceDocument.root.data).Count

if ($keyCount -eq 0) {
    throw "No resource keys were found in $ResourceFile"
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('#nullable enable')
$lines.Add('')
$lines.Add('namespace Cafe.Launcher.UI.Resources;')
$lines.Add('')
$lines.Add('using System.Resources;')
$lines.Add('')
$lines.Add('/// <summary>')
$lines.Add('/// Resource manager for <c>LauncherStrings.resx</c>.')
$lines.Add('/// Generated by scripts/Generate-LauncherStringsDesigner.ps1; do not edit by hand.')
$lines.Add('/// </summary>')
$lines.Add('[System.CodeDom.Compiler.GeneratedCodeAttribute("scripts/Generate-LauncherStringsDesigner.ps1", "1.0.0.0")]')
$lines.Add('[System.Diagnostics.DebuggerNonUserCodeAttribute]')
# internal：宿主不引用本类（它只用 Constants/LocalizationKeys 与 Shell.I18n[...]），
# 表现层与测试（经 UI 程序集的 InternalsVisibleTo）使用 ResourceManager。生成器与产物必须
# 一致，否则重跑脚本会静默放宽表现层公开面（ResxResourceContractTests 守着）。
$lines.Add('internal static class LauncherStrings')
$lines.Add('{')
$lines.Add('    private static ResourceManager? resourceMan;')
$lines.Add('')
$lines.Add('    public static ResourceManager ResourceManager =>')
$lines.Add('        resourceMan ??= new ResourceManager(')
$lines.Add('            "Cafe.Launcher.UI.Resources.LauncherStrings",')
$lines.Add('            typeof(LauncherStrings).Assembly);')
$lines.Add('}')

[System.IO.File]::WriteAllLines(
    $OutputFile,
    $lines,
    [System.Text.UTF8Encoding]::new($false))

Write-Host "Generated the LauncherStrings resource manager for $keyCount keys in $OutputFile."
